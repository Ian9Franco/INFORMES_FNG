import { test } from 'node:test'
import assert from 'node:assert/strict'
import { authFeedback, parseAccessLink, passwordValidation } from '../src/lib/auth-feedback.ts'

test('Email rate limits distinguish password access from email recovery', () => {
  assert.match(authFeedback({ code: 'over_email_send_rate_limit' }), /contraseña.*sin enviar correos/)
  assert.match(authFeedback({ status: 429 }, true), /límite de correos/)
  assert.match(authFeedback({ status: 429 }), /Demasiados intentos/)
  assert.match(authFeedback({ code: 'email_not_confirmed' }), /no evita esa verificación/)
})

test('A password is chosen and confirmed, never generated by the app', () => {
  assert.match(passwordValidation('short', 'short'), /12 caracteres/)
  assert.match(passwordValidation('long-enough-value', 'different-value'), /no coinciden/)
  assert.equal(passwordValidation('long-enough-value', 'long-enough-value'), null)
})

test('Fallback verifies only original links from the configured Auth service', () => {
  const origin = 'https://example.supabase.co'
  assert.deepEqual(parseAccessLink(`${origin}/auth/v1/verify?token=mock-token&type=recovery`, origin), { token_hash: 'mock-token', type: 'recovery' })
  assert.throws(() => parseAccessLink('https://evil.invalid/auth/v1/verify?token=mock-token&type=email', origin))
  assert.throws(() => parseAccessLink(`${origin}/wrong?token=mock-token&type=email`, origin))
  assert.throws(() => parseAccessLink(`${origin}/auth/v1/verify?token=mock-token&type=invite`, origin))
  assert.throws(() => parseAccessLink('http://localhost:3000/#access_token=mock-token', origin))
})
