async function sampleMotion(page, selector) {
  await page.evaluate(selector=>{
    window.feedbackFrames=[];window.feedbackSampling=true
    const sample=()=>{
      if(!window.feedbackSampling)return
      const element=document.querySelector(selector)
      const content=element?.querySelector('.rapid-review-content')
      window.feedbackFrames.push(element?{count:document.querySelectorAll(selector).length,height:element.getBoundingClientRect().height,opacity:Number(getComputedStyle(element).opacity),transform:getComputedStyle(element).transform,inert:element.inert,innerOpacity:content?Number(getComputedStyle(content).opacity):null}:null)
      requestAnimationFrame(sample)
    };sample()
  },selector)
}
async function finishMotion(page) { return page.evaluate(()=>{window.feedbackSampling=false;return window.feedbackFrames}) }
async function startActionGeometry(page, clientId) {
  await page.evaluate(clientId=>{
    window.actionGeometry=[];window.actionGeometrySampling=true
    const sample=()=>{
      if(!window.actionGeometrySampling)return
      const row=document.querySelector(`.review-item[data-client-id="${clientId}"]`)
      window.actionGeometry.push(['.review-row','.review-name','.review-state-label','.review-row-tools','.one-touch-review','.quick-register'].map(selector=>{
        const element=row?.querySelector(selector)
        if(!element)return null
        const {x,y,width,height}=element.getBoundingClientRect()
        return {x,y,width,height}
      }))
      requestAnimationFrame(sample)
    };sample()
  },clientId)
}
async function assertStableActions(page) {
  const frames=await page.evaluate(()=>{window.actionGeometrySampling=false;return window.actionGeometry})
  assert.ok(frames.length>3,'Sample the whole state transition, not only the final frame')
  for(const frame of frames) for(let i=0;i<frame.length;i++) {
    assert.ok(frame[i]&&frames[0][i],'Both action slots must remain mounted')
    for(const dimension of ['x','y','width','height']) assert.ok(Math.abs(frame[i][dimension]-frames[0][i][dimension])<1,`Client controls moved: slot ${i}, ${dimension}, ${frames[0][i][dimension]} → ${frame[i][dimension]}`)
  }
}
async function assertSaveContrast(page) {
  const values=await page.locator('.rapid-save-bar :is(.save-button,.save-next-button)').evaluateAll(buttons=>buttons.map(button=>({color:getComputedStyle(button).color,background:getComputedStyle(button).backgroundColor})))
  const luminance=rgb=>rgb.match(/[\d.]+/g).slice(0,3).map(value=>Number(value)/255).map(value=>value<=.04045?value/12.92:((value+.055)/1.055)**2.4).reduce((sum,value,index)=>sum+value*[.2126,.7152,.0722][index],0)
  assert.equal(values.length,2)
  for(const value of values) { const levels=[luminance(value.color),luminance(value.background)].sort((a,b)=>b-a); assert.ok((levels[0]+.05)/(levels[1]+.05)>=7,'Actual save-button foreground/background must exceed 7:1') }
}
function broadcast(row) {
  for (const ws of sockets) ws.send(JSON.stringify([null,null,`realtime:workspace:${uid}`,'postgres_changes',{ids:[1],data:{schema:'public',table:'fng_records',type:row.version===1?'INSERT':'UPDATE',columns:[],record:row,old_record:{}}}]))
}
async function device() {
  const context = await browser.newContext({ viewport:{width:1280,height:900} })
  await context.addInitScript(({ jwt,user }) => localStorage.setItem('sb-zxhxerhksohymmyofvqb-auth-token',JSON.stringify({access_token:jwt,refresh_token:'mock-refresh',token_type:'bearer',expires_in:3600,expires_at:Math.floor(Date.now()/1000)+3600,user})),{jwt,user})
  await context.route('**/auth/v1/**',route => route.fulfill({json:user}))
  await context.route('**/rest/v1/**',async route => {
    const request = route.request(), parsed = new URL(request.url())
    if (parsed.pathname.endsWith('/rpc/fng_apply_changes')) {
      const { changes } = request.postDataJSON()
      for(const change of changes) {
        const existing=rows.get(key(change))
        if (existing && existing.version!==change.expectedVersion && JSON.stringify(existing.payload)!==JSON.stringify(change.payload)) return route.fulfill({status:409,json:{code:'40001',message:`FNG_CONFLICT:${key(change)}`}})
      }
      const updated=changes.map(change=>({...make(change.kind,change.id,change.payload,(rows.get(key(change))?.version??0)+1),deleted:change.deleted}))
      updated.forEach(row=>{rows.set(key(row),row);broadcast(row)})
      writes+=changes.length
      return route.fulfill({json:updated})
    }
    let selected = [...rows.values()]
    for(const [field,condition] of parsed.searchParams) {
      if (!['kind','id','user_id','review_date'].includes(field)) continue
      const [op,...rest]=condition.split('.'), value=rest.join('.')
      selected=selected.filter(row=>op==='eq'?row[field]===value:op==='neq'?row[field]!==value:op==='gte'?row[field]>=value:op==='lt'?row[field]<value:op==='in'?value.replace(/[()]/g,'').split(',').includes(row[field]):true)
    }
    return route.fulfill({json:request.headers().accept?.includes('object+json')?(selected[0]??null):selected})
  })
  const page = await context.newPage()
  pages.push(page)
  page.on('pageerror',error=>errors.push(error.message))
  await page.routeWebSocket('**/realtime/v1/**',ws=>{
    sockets.add(ws)
    ws.onMessage(message=>{
      const [joinRef,ref,topic,event,payload]=JSON.parse(String(message))
      if(event==='phx_join') ws.send(JSON.stringify([joinRef,ref,topic,'phx_reply',{status:'ok',response:{postgres_changes:(payload.config.postgres_changes??[]).map(item=>({...item,id:1}))}}]))
      if(event==='heartbeat') ws.send(JSON.stringify([joinRef,ref,topic,'phx_reply',{status:'ok',response:{}}]))
    })
    ws.onClose(()=>sockets.delete(ws))
  })
  await page.goto(url)
  await page.getByRole('heading',{name:'Mi jornada',exact:true}).waitFor()
  await page.getByRole('button',{name:'Mi cuenta · DB activa',exact:true}).waitFor()
  return {context,page}
}
